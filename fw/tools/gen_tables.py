#!/usr/bin/env python3
"""Tables for fw/ from the validated Python solver (nec/cap_demand.py, §5.1).

Run:  python3 fw/tools/gen_tables.py

fw/test/tnet_vectors.inc    test vectors: the 27 band edges plus the two interpolated 160 m points,
                            Z at the tuner through 40 ft of 600 ohm line at VF 0.95, C1 = UCSX-700-15S,
                            and what cap_demand.best() chooses there (lowest roller current in range)
fw/core/src/seed_priors.inc the factory priors (§6A.7 option 2, §7.6), one per 1 % profile segment
                            (fw/core/src/freq.cpp): the feedpoint Z interpolated linearly between the
                            NEC points on the band, carried through the feeder at the segment center,
                            and its solution
fw/core/src/roller_model.inc the roller's inductance against wheel turns on the deck at 1 MHz, from
                            the NEC sweep (nec/out/roller_vna_k*_deck.csv), until commissioning
                            measures it (§9 items 44, 54)
"""
import cmath, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'nec'))
import cap_demand as cd  # noqa: E402

OUT = os.path.join(HERE, '..', 'test', 'tnet_vectors.inc')
SEED = os.path.join(HERE, '..', 'core', 'src', 'seed_priors.inc')
ROLLER = os.path.join(HERE, '..', 'core', 'src', 'roller_model.inc')
NEC_OUT = os.path.join(HERE, '..', '..', 'nec', 'out')
BANDS = [('160m', 1.800, 2.000), ('80m', 3.500, 4.000), ('60m', 5.330, 5.406), ('40m', 7.000, 7.300),
         ('30m', 10.100, 10.150), ('20m', 14.000, 14.350), ('17m', 18.068, 18.168), ('15m', 21.000, 21.450),
         ('12m', 24.890, 24.990), ('10m', 28.000, 29.700)]                    # kBands, freq.cpp


def segments():
    """(band, center MHz) for every profile segment, as freq.cpp's segment_center()."""
    out = []
    for name, lo, hi in BANDS:
        n = math.ceil((hi - lo) / (0.01 * lo) - 1e-9)
        for k in range(n):
            out.append((name, min(lo + (k + 0.5) * 0.01 * lo, (lo * (1 + 0.01 * k) + hi) / 2)))
    return out


def feedpoint(name, f):
    """NEC feedpoint Z on a band, linear in frequency between its points, held flat past the ends."""
    pts = sorted((p[1], p[2]) for p in cd.pts if p[0] == name)
    if f <= pts[0][0]:
        return pts[0][1]
    for (f0, z0), (f1, z1) in zip(pts, pts[1:]):
        if f <= f1:
            return z0 + (z1 - z0) * (f - f0) / (f1 - f0)
    return pts[-1][1]


def g(v):
    return '%.17g' % v


def main():
    c1r = cd.C1_PARTS['UCSX-700-15S']
    rows = []
    for band, f, ZL in cd.pts:
        Z = cd.zin(f, ZL, 40.0, 0.95)
        s = cd.best(f, Z, c1r)
        vals = [g(f), g(ZL.real), g(ZL.imag), g(Z.real), g(Z.imag)]
        if s:
            vals += ['true'] + [g(s[k]) for k in ('L', 'C1', 'C2', 'IL', 'VC1', 'VC2', 'VL')]
        else:
            vals += ['false'] + ['0'] * 7
        rows.append('{"%s", %s},' % (band, ', '.join(vals)))
    with open(OUT, 'w') as fh:
        fh.write('// Generated by fw/tools/gen_tables.py from nec/cap_demand.py. Do not edit.\n')
        fh.write('// band, MHz, R, X at the feedpoint (NEC), R, X at the tuner; solved; L (H), C1 (F), C2 (F), I_L (A RMS), '
                 'V_C1, V_C2, V_L (V pk)\n')
        fh.write(f'// Parts: C1 {c1r[0]:.4g}-{c1r[1]:.4g} F, C2 {cd.C2R[0]:.4g}-{cd.C2R[1]:.4g} F, '
                 f'L {cd.lgrid(cd.L_MAX)[0]:.4g}-{cd.L_MAX:.4g} H, 4000-point log grid\n')
        fh.write('\n'.join(rows) + '\n')
    print(f'{len(rows)} vectors, {sum("true" in r for r in rows)} solved -> {os.path.relpath(OUT)}')

    seeds = []
    for name, f in segments():
        Z = cd.zin(f, feedpoint(name, f), 40.0, 0.95)
        s = cd.best(f, Z, c1r)
        vals = [g(f), g(Z.real), g(Z.imag)]
        vals += [g(s['C1']), g(s['L']), g(s['C2']), 'true'] if s else ['0', '0', '0', 'false']
        seeds.append('{%s},  // %s' % (', '.join(vals), name))
    with open(SEED, 'w') as fh:
        fh.write('// Generated by fw/tools/gen_tables.py from nec/cap_demand.py. Do not edit.\n')
        fh.write('// segment center MHz, R, X at the tuner (NEC model, 40 ft at VF 0.95); C1 (F), L (H), C2 (F) '
                 'that match it; matched\n')
        fh.write('\n'.join(seeds) + '\n')
    print(f'{len(seeds)} segment priors, {sum("true}" in s for s in seeds)} matched -> {os.path.relpath(SEED)}')


def roller_model():
    rows = ['{0, 0},  // wheel at the end: no turns in circuit']
    for k in range(1, 23):
        with open(os.path.join(NEC_OUT, f'roller_vna_k{k}_deck.csv')) as fh:
            hdr, first = fh.read().splitlines()[:2]
        assert hdr.split(',')[3] == 'L_uH' and abs(float(first.split(',')[0]) - 1.0) < 1e-9
        rows.append('{%d, %se-6},' % (k, first.split(',')[3]))
    with open(ROLLER, 'w') as fh:
        fh.write('// Generated by fw/tools/gen_tables.py from nec/out/roller_vna_k*_deck.csv. Do not edit.\n')
        fh.write('// wheel turns from the low end, inductance (H) on the deck at 1 MHz\n')
        fh.write('\n'.join(rows) + '\n')
    print(f'{len(rows)} roller points -> {os.path.relpath(ROLLER)}')


if __name__ == '__main__':
    main()
    roller_model()
